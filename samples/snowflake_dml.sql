-- Sample Snowflake DML statements demonstrating syntax differences

-- 1. SELECT with various Snowflake-specific constructs
SELECT
    o.ORDER_ID,
    o.CUSTOMER_ID,
    NVL(o.DISCOUNT, 0)                             AS DISCOUNT,
    o.AMOUNT * (1 - NVL(o.DISCOUNT, 0) / 100)     AS FINAL_AMOUNT,
    TO_CHAR(o.ORDER_DATE, 'YYYY-MM-DD HH24:MI:SS') AS ORDER_DATETIME,
    CASE
        WHEN o.AMOUNT > 1000 THEN 'HIGH'
        WHEN o.AMOUNT > 500  THEN 'MEDIUM'
        ELSE 'LOW'
    END                                             AS VALUE_TIER,
    GET_PATH(o.METADATA, 'shipping.carrier')        AS CARRIER,
    o.TAGS:priority::STRING                         AS PRIORITY,
    ARRAY_CONTAINS('EXPRESS'::VARIANT, o.TAGS)     AS IS_EXPRESS,
    DATEADD('day', 7, o.ORDER_DATE)                AS ESTIMATED_DELIVERY,
    DATEDIFF('day', o.ORDER_DATE, CURRENT_DATE())  AS DAYS_AGO,
    RATIO_TO_REPORT(o.AMOUNT) OVER (
        PARTITION BY o.REGION
        ORDER BY o.ORDER_DATE
    )                                               AS REVENUE_SHARE
FROM MYDB.PUBLIC.ORDERS o
WHERE o.ORDER_DATE >= DATEADD('month', -6, CURRENT_DATE())
  AND o.STATUS NOT IN ('CANCELLED', 'REFUNDED')
SAMPLE (10 ROWS);


-- 2. INSERT OVERWRITE
INSERT OVERWRITE INTO MYDB.PUBLIC.DAILY_SNAPSHOT
SELECT
    CURRENT_DATE()                                  AS SNAPSHOT_DATE,
    STATUS,
    COUNT(*)                                        AS ORDER_COUNT,
    SUM(AMOUNT)                                     AS TOTAL_AMOUNT
FROM MYDB.PUBLIC.ORDERS
GROUP BY STATUS;


-- 3. MERGE statement (mostly compatible)
MERGE INTO MYDB.PUBLIC.CUSTOMERS tgt
USING (
    SELECT
        CUSTOMER_ID,
        SUM(AMOUNT)   AS TOTAL_SPENT,
        MAX(ORDER_DATE) AS LAST_ORDER
    FROM MYDB.PUBLIC.ORDERS
    WHERE ORDER_DATE >= DATEADD('day', -30, CURRENT_DATE())
    GROUP BY CUSTOMER_ID
) src ON tgt.CUSTOMER_ID = src.CUSTOMER_ID
WHEN MATCHED THEN
    UPDATE SET
        tgt.LIFETIME_VALUE = tgt.LIFETIME_VALUE + src.TOTAL_SPENT,
        tgt.LAST_ORDER_DATE = src.LAST_ORDER,
        tgt.UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN
    INSERT (CUSTOMER_ID, LIFETIME_VALUE, LAST_ORDER_DATE, CREATED_AT)
    VALUES (src.CUSTOMER_ID, src.TOTAL_SPENT, src.LAST_ORDER, CURRENT_TIMESTAMP());


-- 4. UPDATE with USING pattern
UPDATE MYDB.PUBLIC.PRODUCTS p
SET p.STOCK_COUNT = p.STOCK_COUNT - i.QUANTITY,
    p.UPDATED_AT  = CURRENT_TIMESTAMP()
FROM MYDB.PUBLIC.ORDER_ITEMS i
WHERE p.PRODUCT_ID = i.PRODUCT_ID
  AND i.ORDER_DATE = CURRENT_DATE();


-- 5. LATERAL FLATTEN (semi-structured)
SELECT
    o.ORDER_ID,
    f.value::STRING                                 AS TAG
FROM MYDB.PUBLIC.ORDERS o,
LATERAL FLATTEN(input => o.TAGS) f
WHERE f.value IS NOT NULL;


-- 6. Time travel query
SELECT *
FROM MYDB.PUBLIC.ORDERS
AT(TIMESTAMP => DATEADD('hour', -1, CURRENT_TIMESTAMP()));


-- 7. Window functions
SELECT
    ORDER_ID,
    CUSTOMER_ID,
    AMOUNT,
    ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY ORDER_DATE DESC) AS RN,
    LAG(AMOUNT, 1, 0) OVER (PARTITION BY CUSTOMER_ID ORDER BY ORDER_DATE) AS PREV_AMOUNT,
    SUM(AMOUNT) OVER (PARTITION BY CUSTOMER_ID
                      ORDER BY ORDER_DATE
                      ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RUNNING_TOTAL,
    CONDITIONAL_CHANGE_EVENT(STATUS) OVER (
        PARTITION BY CUSTOMER_ID ORDER BY ORDER_DATE
    ) AS STATUS_CHANGES
FROM MYDB.PUBLIC.ORDERS;
